#!/usr/bin/env python3
"""Export the shared catalog to native platform resources; --check detects drift."""
import argparse
import json
from pathlib import Path
import re
import sys
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'localization/catalog.json'
LANGUAGES = ('ro', 'en', 'ru')


def outputs(catalog, platforms):
    result = {}
    for platform in platforms:
        entries = [e for e in catalog['entries'] if e['platform'] == platform]
        if platform in ('android', 'windows'):
            for lang in LANGUAGES:
                lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>' if platform == 'android' else '<root>']
                if platform == 'windows':
                    for name, value in [('resmimetype', 'text/microsoft-resx'), ('version', '2.0')]:
                        lines.append(f'  <resheader name="{name}"><value>{value}</value></resheader>')
                for e in entries:
                    value = e['translations'].get(lang, e['translations'].get('en', e['translations']['ro']))
                    key = escape(e['key'], {'"': '&quot;'})
                    if platform == 'android':
                        def android_text(v):
                            # Preserve existing Android escapes; quote strings to protect apostrophes and whitespace.
                            return escape(v.replace('\\\'', "'").replace('"', '\\"')).replace("'", "\\'")
                        if isinstance(value, dict):
                            lines.append(f'  <plurals name="{key}">')
                            for quantity, text in value.items():
                                lines.append(f'    <item quantity="{quantity}">{android_text(text)}</item>')
                            lines.append('  </plurals>')
                        else:
                            lines.append(f'  <string name="{key}">{android_text(value)}</string>')
                    else:
                        lines.append(f'  <data name="{key}" xml:space="preserve"><value>{escape(value)}</value></data>')
                lines.append('</resources>' if platform == 'android' else '</root>')
                folder = {'ro': 'values', 'en': 'values-en', 'ru': 'values-ru'}[lang] if platform == 'android' else {'ro': 'ro-RO', 'en': 'en-US', 'ru': 'ru-RU'}[lang]
                path = f'android/app/src/main/res/{folder}/strings.xml' if platform == 'android' else f'windows/src/MoldSign.App/Strings/{folder}/Resources.resw'
                result[path] = '\n'.join(lines) + '\n'
        elif platform == 'apple':
            strings = {}
            for e in entries:
                strings[e['key']] = {'localizations': {lang: {'stringUnit': {'state': 'translated', 'value': value}} for lang, value in e['translations'].items()}}
            result['apple/Apps/Shared/Resources/Localizable.xcstrings'] = json.dumps({'sourceLanguage':'ro', 'strings':strings, 'version':'1.0'}, ensure_ascii=False, indent=2)+'\n'
            cases = '\n'.join('        case '+e['key'] for e in entries)
            result['apple/Apps/Shared/Services/L10n.swift'] = '''// Generated by scripts/localize.py; edit localization/catalog.json.
import Foundation

enum L10n {
    enum Key: String, CaseIterable {
'''+cases+'''
    }
    static func text(_ key: Key, _ arguments: CVarArg...) -> String {
        let languages = UserDefaults.standard.stringArray(forKey: "AppleLanguages") ?? Locale.preferredLanguages
        let code = languages.first.map { String($0.prefix(2)) } ?? "ro"
        let bundle = Bundle.main.path(forResource: code, ofType: "lproj").flatMap(Bundle.init(path:)) ?? .main
        let template = bundle.localizedString(forKey: key.rawValue, value: nil, table: nil)
        return arguments.isEmpty ? template : String(format: template, locale: Locale(identifier: code), arguments: arguments)
    }
}
'''
        elif platform == 'linux':
            table = {e['key']:e['translations'] for e in entries}
            swift = json.dumps(table, ensure_ascii=False, indent=2)
            # A JSON resource embedded as a raw literal avoids Swift keyword/key escaping differences.
            result['linux/Sources/MoldSignGnome/Infrastructure/Localization/L10n.swift'] = '''// Generated by scripts/localize.py; edit localization/catalog.json.
import Foundation

enum L10n {
    enum Key: String, CaseIterable {
'''+ '\n'.join('        case '+e['key'] for e in entries) + '''
    }
    static var language: String?
    static func text(_ key: Key) -> String {
        let code = language ?? Locale.current.language.languageCode?.identifier ?? "ro"
        return translations[key.rawValue]?[code] ?? translations[key.rawValue]?["ro"] ?? key.rawValue
    }
    private static let translations: [String: [String: String]] = {
        let data = Data(#"""
'''+swift+'''
"""#.utf8)
        return (try? JSONDecoder().decode([String: [String: String]].self, from: data)) ?? [:]
    }()
}
'''
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--platform', action='append', choices=['apple','macos','ios','android','windows','linux'])
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--require-complete', action='store_true')
    args = parser.parse_args()
    catalog = json.loads(CATALOG.read_text())
    platforms = list(dict.fromkeys('apple' if p in ('macos', 'ios') else p for p in (args.platform or ['apple','android','windows','linux'])))
    seen = set()
    def placeholders(value):
        if isinstance(value, dict):
            # A plural category can omit an argument when its quantity implies a single value.
            tokens = set()
            for variant in value.values():
                tokens.update(re.findall(r"(?<!%)%(?:[0-9]+\$)?(?:lld|ld|[dsf@])|\{[0-9]+\}", variant))
            return sorted(tokens)
        return sorted(re.findall(r"(?<!%)%(?:[0-9]+\$)?(?:lld|ld|[dsf@])|\{[0-9]+\}", value))
    for entry in catalog['entries']:
        identity = (entry['platform'], entry['key'])
        if identity in seen:
            raise SystemExit(f'Duplicate localization: {identity}')
        seen.add(identity)
        if entry['platform'] in ('apple', 'linux', 'android') and not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*', entry['key']):
            raise SystemExit(f'Localization keys must be stable identifiers: {identity}')
        source_tokens = placeholders(entry['translations']['ro'])
        for lang, value in entry['translations'].items():
            if placeholders(value) != source_tokens:
                raise SystemExit(f'Formatting arguments differ for {lang}: {identity}')
        if args.require_complete and entry['platform'] in platforms:
            missing = set(LANGUAGES) - entry['translations'].keys()
            if missing:
                raise SystemExit(f'Missing {sorted(missing)}: {identity}')
    failed = []
    for path, body in outputs(catalog, platforms).items():
        file = ROOT/path
        if args.check:
            if not file.exists() or file.read_text() != body:
                failed.append(path)
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(body)
    if failed:
        print('Localization exports differ:\n'+'\n'.join(failed), file=sys.stderr)
        return 1
    if args.check:
        # Typed APIs prevent accidental display-copy lookups. Check source as well as resources,
        # so adding an unkeyed screen cannot silently pass the generated-file drift check.
        violations = []
        for platform, folder in [('apple', 'apple/Apps'), ('linux', 'linux/Sources')]:
            if platform not in platforms:
                continue
            for file in (ROOT / folder).rglob('*.swift'):
                if file.name == 'L10n.swift':
                    continue
                for number, line in enumerate(file.read_text().splitlines(), 1):
                    prose_label = re.search(r'(?<![A-Za-z])(?:Text|Label|Button|Toggle|Section|Picker|LabeledContent|navigationTitle|accessibilityLabel|help|alert|confirmationDialog)\(\s*"([^"\n]*)"', line)
                    unkeyed_prose = prose_label and not prose_label.group(1).startswith('\\(') and bool(re.search(r'[A-Za-zÀ-žА-я]', prose_label.group(1)))
                    if unkeyed_prose or re.search(r'String\(localized:\s*"|L10n\.text\(\s*"|localized\(\s*"', line):
                        violations.append(f'{file.relative_to(ROOT)}:{number}')
        if violations:
            print('Use a stable typed localization identifier:\n'+'\n'.join(violations), file=sys.stderr)
            return 1
    print('Localization exports '+('match' if args.check else 'written')+': '+', '.join(platforms))
    return 0


if __name__ == '__main__':
    sys.exit(main())
