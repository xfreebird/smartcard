#!/usr/bin/env python3
"""Export official service shortcuts and bundled website icons to native platforms."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit
root = Path(__file__).resolve().parents[1]
items = json.loads((root / 'spec/browser/services.json').read_text())
assert len({i['id'] for i in items}) == len(items)
for item in items:
    url = urlsplit(item['url'])
    assert url.scheme == 'https' and url.hostname and not url.username and not url.password
    assert item['icon'].replace('_', '').isalnum()
swift = '// Generated by scripts/export-browser-services.py; edit spec/browser/services.json.\nimport Foundation\n\nstruct PortalService: Identifiable {\n    let id: String\n    let name: String?\n    let titleKey: L10n.Key?\n    let url: URL\n    let imageName: String\n    var title: String { name ?? L10n.text(titleKey!) }\n    static let all: [PortalService] = [\n'
for item in items:
    name = json.dumps(item['title']) if 'title' in item else 'nil'
    key = '.' + item['titleKey'] if 'titleKey' in item else 'nil'
    swift += f'        .init(id: "{item["id"]}", name: {name}, titleKey: {key}, url: URL(string: "{item["url"]}")!, imageName: "PortalService_{item["icon"]}"),\n'
swift += '    ]\n}\n'
kotlin = '// Generated by scripts/export-browser-services.py; edit spec/browser/services.json.\npackage md.moldsign.app.ui.screens\n\nimport md.moldsign.app.R\n\ninternal data class PortalService(val name: String?, val titleResource: Int?, val url: String, val imageResource: Int) {\n    companion object {\n        val all = listOf(\n'
for item in items:
    name = json.dumps(item['title']) if 'title' in item else 'null'
    key = 'R.string.' + item['titleKey'] if 'titleKey' in item else 'null'
    kotlin += f'            PortalService({name}, {key}, "{item["url"]}", R.drawable.portal_service_{item["icon"]}),\n'
kotlin += '        )\n    }\n}\n'
outputs = {'apple/Apps/Shared/Services/PortalService.swift': swift.encode(), 'android/app/src/main/kotlin/md/moldsign/app/ui/screens/PortalService.kt': kotlin.encode()}
assets = 'apple/Apps/Shared/Resources/PortalServices.xcassets'
outputs[f'{assets}/Contents.json'] = b'{"info":{"author":"xcode","version":1}}\n'
for icon in sorted({item['icon'] for item in items}):
    data = (root / f'spec/browser/icons/{icon}.png').read_bytes()
    folder = f'{assets}/PortalService_{icon}.imageset'
    contents = {'images':[{'idiom':'universal','filename':'icon.png'}], 'info':{'author':'xcode','version':1}, 'properties':{'template-rendering-intent':'original'}}
    outputs[f'{folder}/Contents.json'] = (json.dumps(contents,indent=2)+'\n').encode()
    outputs[f'{folder}/icon.png'] = data
    outputs[f'android/app/src/main/res/drawable-nodpi/portal_service_{icon}.png'] = data
parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
for path, content in outputs.items():
    target = root / path
    if args.check:
        if not target.exists() or target.read_bytes() != content:
            raise SystemExit(f'Browser shortcut export differs: {path}')
    else:
        target.parent.mkdir(parents=True,exist_ok=True)
        target.write_bytes(content)
print('Browser service exports match' if args.check else 'Browser service exports updated')
