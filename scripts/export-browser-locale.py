#!/usr/bin/env python3
"""Export the same document-start locale policy to Apple and Android."""
import argparse
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = (root / "spec/browser/locale.js").read_text()
assert source.count("__APP_LANGUAGE__") == 1
assert '"""' not in source and "$" not in source and "\\(" not in source
swift = ('// Generated by scripts/export-browser-locale.py; edit spec/browser/locale.js.\n'
         'import Foundation\n\n'
         'enum BrowserLocaleScript {\n'
         '    static func source(language: String) -> String {\n'
         '        let language = ["ro", "en", "ru"].contains(language) ? language : "ro"\n'
         '        return """\n' +
         "".join("        " + line + "\n" for line in source.splitlines()) +
         '        """.replacingOccurrences(of: "__APP_LANGUAGE__", with: language)\n'
         '    }\n}\n')
kotlin = ('// Generated by scripts/export-browser-locale.py; edit spec/browser/locale.js.\n'
          'package md.moldsign.app.ui.screens\n\n'
          'internal object BrowserLocaleScript {\n'
          '    fun source(language: String): String {\n'
          '        val code = language.takeIf { it in setOf("ro", "en", "ru") } ?: "ro"\n'
          '        return """\n' +
          "".join("            " + line + "\n" for line in source.splitlines()) +
          '        """.trimIndent().replace("__APP_LANGUAGE__", code)\n'
          '    }\n}\n')
outputs = {
    "apple/Apps/Shared/Services/BrowserLocaleScript.swift": swift,
    "android/app/src/main/kotlin/md/moldsign/app/ui/screens/BrowserLocaleScript.kt": kotlin,
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
for name, content in outputs.items():
    path = root / name
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"Browser locale export differs: {name}")
    else:
        path.write_text(content)
print("Browser locale exports match" if args.check else "Browser locale exports updated")
