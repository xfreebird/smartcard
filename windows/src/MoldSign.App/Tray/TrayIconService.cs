using System.Runtime.InteropServices;
using H.NotifyIcon;
using Microsoft.UI.Dispatching;
using Microsoft.UI.Xaml.Controls;
using Microsoft.Win32;
using MoldSign.App.Services;
using Windows.UI.ViewManagement;

namespace MoldSign.App.Tray;

/// <summary>
/// Notification-area icon (WIN-04; H.NotifyIcon.WinUI) with the two-state dot of docs/10 §0.2b (UX-11): GREEN when at
/// least one card is inserted (reading, ready or signing), GRAY otherwise (no reader, empty reader, only failing cards).
/// The five-state light (§0.1) stays inside the flyout and window headers. Left click toggles the flyout (docs/10 §4.6,
/// mirrors the macOS popover); right click shows the native menu (Deschide fereastra / Ieșire).
///
/// Icons: Assets/Tray/tray-&lt;connected|none&gt;-&lt;dark|light&gt;.ico, generated by scripts/make-icons.py from
/// design/icons/tray.svg. The glyph is monochrome for the taskbar theme (white on a dark taskbar, near-black on a light
/// one: Windows does not tint tray icons), only the dot is colored, and the tooltip always says the same thing as the
/// dot ("eSemnBun · Card conectat · ION POPESCU", "eSemnBun · Niciun card conectat").
/// </summary>
public sealed partial class TrayIconService(Action toggleFlyout, Action openWindow, Action quit) : IDisposable
{
    private const int SmCxSmIcon = 49;
    private const int SmCySmIcon = 50;

    private readonly Dictionary<string, System.Drawing.Icon> _icons = new(StringComparer.Ordinal);
    private readonly UISettings _uiSettings = new();
    private TaskbarIcon? _icon;
    private DispatcherQueue? _ui;
    private bool _connected;
    private string? _shownFile;

    public void Create()
    {
        if (_icon is not null) return;
        _ui = DispatcherQueue.GetForCurrentThread();

        var menu = new MenuFlyout();
        menu.Items.Add(new MenuFlyoutItem { Text = Loc.Get("Tray_OpenWindow"), Command = new RelayCommand(openWindow) });
        menu.Items.Add(new MenuFlyoutSeparator());
        menu.Items.Add(new MenuFlyoutItem { Text = Loc.Get("Tray_Quit"), Command = new RelayCommand(quit) });

        _icon = new TaskbarIcon
        {
            ToolTipText = AppInfo.ProductName,
            ContextMenuMode = ContextMenuMode.PopupMenu,
            ContextFlyout = menu,
            LeftClickCommand = new RelayCommand(toggleFlyout),
            NoLeftClickDelay = true,
        };
        Update(connected: false, Loc.Get("Tray_None"));
        _icon.ForceCreate();

        // Taskbar light/dark switch: pick the matching glyph (raised on a background thread).
        _uiSettings.ColorValuesChanged += OnColorValuesChanged;
        // TODO(WIN-04): accept files dropped on the flyout/taskbar entry; the notification area itself has no drop target.
    }

    /// <summary>Green (card connected) or gray dot, and the matching tooltip. Call on the UI thread.</summary>
    public void Update(bool connected, string label)
    {
        if (_icon is null) return;
        _connected = connected;
        _icon.ToolTipText = $"{AppInfo.ProductName} · {label}";
        var file = $"tray-{(connected ? "connected" : "none")}-{(TaskbarIsLight() ? "light" : "dark")}.ico";
        if (file == _shownFile) return;
        if (Load(file) is { } icon)
        {
            _icon.Icon = icon;
            _shownFile = file;
        }
    }

    public void Dispose()
    {
        _uiSettings.ColorValuesChanged -= OnColorValuesChanged;
        _icon?.Dispose();
        _icon = null;
        foreach (var icon in _icons.Values) icon.Dispose();
        _icons.Clear();
    }

    private void OnColorValuesChanged(UISettings sender, object args) =>
        _ui?.TryEnqueue(() => Update(_connected, AppState.Current.TrayLabel));

    /// <summary>The .ico frame closest to the small-icon size of the current DPI (16 px at 100 %, 24 at 150 %…).</summary>
    private System.Drawing.Icon? Load(string file)
    {
        if (_icons.TryGetValue(file, out var cached)) return cached;
        var path = Path.Combine(AppContext.BaseDirectory, "Assets", "Tray", file);
        if (!File.Exists(path)) return null;
        var dpi = GetDpiForSystem();
        var size = new System.Drawing.Size(GetSystemMetricsForDpi(SmCxSmIcon, dpi), GetSystemMetricsForDpi(SmCySmIcon, dpi));
        var icon = new System.Drawing.Icon(path, size.Width > 0 ? size : new System.Drawing.Size(16, 16));
        _icons[file] = icon;
        return icon;
    }

    /// <summary>HKCU\…\Themes\Personalize\SystemUsesLightTheme = 1: light taskbar (Windows 11 "Light" mode).</summary>
    private static bool TaskbarIsLight()
    {
        try
        {
            using var key = Registry.CurrentUser.OpenSubKey(@"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize");
            return key?.GetValue("SystemUsesLightTheme") is int value && value != 0;
        }
        catch (Exception)
        {
            return false; // Windows 10 default: dark taskbar
        }
    }

    [LibraryImport("user32.dll")]
    private static partial uint GetDpiForSystem();

    [LibraryImport("user32.dll")]
    private static partial int GetSystemMetricsForDpi(int nIndex, uint dpi);
}
